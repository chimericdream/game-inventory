// Screenshot helper. Every image is also recorded in screenshots/INDEX.md with a description,
// so whoever reviews the images (a person or another agent) knows what state each one shows.
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';

import type { Locator, Page } from '@playwright/test';

export const OUT = path.resolve(process.cwd(), 'screenshots');
const MANIFEST = path.join(OUT, 'manifest.json');

interface Entry {
  file: string;
  viewer: string;
  viewport: string;
  scheme: string;
  description: string;
}

function record(entry: Entry) {
  const all: Entry[] = existsSync(MANIFEST) ? JSON.parse(readFileSync(MANIFEST, 'utf8')) : [];
  const next = all.filter((e) => e.file !== entry.file).concat(entry);
  next.sort((a, b) => a.file.localeCompare(b.file));
  writeFileSync(MANIFEST, JSON.stringify(next, null, 2));

  const lines = [
    '# Screenshot index',
    '',
    'Generated by `pnpm shots`. Every image is a full-page capture of the production build with',
    'seeded demo data. Mantine default theme, `auto` color scheme (light unless noted).',
    '',
  ];
  let folder = '';
  for (const e of next) {
    const [dir] = e.file.split('/');
    if (dir !== folder) {
      folder = dir!;
      lines.push(`## ${folder}`, '');
    }
    lines.push(`- \`${e.file}\` (${e.viewer}, ${e.viewport}, ${e.scheme}): ${e.description}`);
  }
  writeFileSync(path.join(OUT, 'INDEX.md'), lines.join('\n') + '\n');
}

export interface ShotOptions {
  /** Which identity is looking at the page. */
  viewer?: string;
  /** Capture only this element instead of the page. */
  of?: Locator;
  fullPage?: boolean;
  scheme?: 'light' | 'dark';
}

/**
 * Saves `screenshots/<folder>/<name>.png`. `name` should be numbered and descriptive, such as
 * `03-form-validation-error`, so the folder reads in workflow order.
 */
export async function shot(
  page: Page,
  folder: string,
  name: string,
  description: string,
  opts: ShotOptions = {},
) {
  const file = `${folder}/${name}.png`;
  const abs = path.join(OUT, file);
  mkdirSync(path.dirname(abs), { recursive: true });
  await page.evaluate(() => document.fonts.ready);
  await page.waitForTimeout(350); // let Mantine transitions and image loads settle
  if (opts.of) {
    await opts.of.screenshot({ path: abs, animations: 'disabled', caret: 'hide' });
  } else if (opts.fullPage === false) {
    await page.screenshot({ path: abs, animations: 'disabled', caret: 'hide' });
  } else {
    // The header and sidebar are position: fixed, so Playwright's fullPage mode would draw them
    // wherever the page happens to be scrolled and cut the sidebar at one screen height. Instead
    // grow the viewport to the whole document and capture that, from the top.
    const original = page.viewportSize();
    await page.evaluate(() => window.scrollTo(0, 0));
    const height = await page.evaluate(() => document.documentElement.scrollHeight);
    if (original)
      await page.setViewportSize({
        width: original.width,
        height: Math.min(Math.max(height, original.height), 12000),
      });
    await page.waitForTimeout(250);
    await page.screenshot({ path: abs, animations: 'disabled', caret: 'hide' });
    if (original) await page.setViewportSize(original);
  }
  const vp = page.viewportSize();
  record({
    file,
    viewer: opts.viewer ?? 'admin',
    viewport: vp ? `${vp.width}x${vp.height}` : 'unknown',
    scheme: opts.scheme ?? 'light',
    description,
  });
}
